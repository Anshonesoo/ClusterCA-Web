export type TranslationKey = keyof typeof zh;

const dictionaries: Record<Language, Record<TranslationKey, string>> = { zh, en };

export const translate = (language: Language): ((key: TranslationKey) => string) => {
  const dict = dictionaries[language];
  return (key: TranslationKey): string => dict[key] ?? zh[key] ?? String(key);
};

export const formatText = (template: string, values: Record<string, string | number>): string => {
  let result = template;
  for (const [key, value] of Object.entries(values)) result = result.replaceAll(`{${key}}`, String(value));
  return result;
};
